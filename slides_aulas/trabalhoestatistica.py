def formatar_reais(x, pos=None):
    if x >= 1e6:   return f'R${x/1e6:.1f}M'
    if x >= 1e3:   return f'R${x/1e3:.0f}K'
    return f'R${x:.0f}'

def rotular_outliers(ax, serie, entidades):
    """Anota os outliers extremos com o nome do órgão."""
    q1, q3 = serie.quantile(0.25), serie.quantile(0.75)
    iqr = q3 - q1
    limite_sup = q3 + 1.5 * iqr
    limite_inf = q1 - 1.5 * iqr
    outliers = serie[(serie > limite_sup) | (serie < limite_inf)]
    for idx in outliers.index:
        val = serie[idx]
        label = entidades[idx][:28]  # limita o texto
        ax.annotate(
            label,
            xy=(0, val),
            xytext=(0.55, val),
            fontsize=7,
            color='#c0392b',
            arrowprops=dict(arrowstyle='->', color='#c0392b', lw=0.8),
        )

fig, axes = plt.subplots(4, 3, figsize=(18, 22))
axes = axes.flatten()

for i, (col, titulo) in enumerate(VARIAVEIS):
    ax = axes[i]
    serie = df[col].copy()

    bp = ax.boxplot(
        serie,
        vert=True,
        patch_artist=True,
        widths=0.4,
        boxprops=dict(facecolor='#AED6F1', color='#2C3E50'),
        medianprops=dict(color='#E74C3C', linewidth=2.5),
        whiskerprops=dict(color='#2C3E50', linewidth=1.5),
        capprops=dict(color='#2C3E50', linewidth=1.5),
        flierprops=dict(marker='o', markerfacecolor='#E74C3C', markersize=5, linestyle='none', alpha=0.7),
    )

    # Linha da média
    media = serie.mean()
    ax.axhline(media, color='#27AE60', linestyle='--', linewidth=1.5, label=f'Média: {formatar_reais(media)}')

    # Estatísticas no título
    q1, med, q3 = serie.quantile(0.25), serie.median(), serie.quantile(0.75)
    n_outliers = int(((serie < q1 - 1.5*(q3-q1)) | (serie > q3 + 1.5*(q3-q1))).sum())

    ax.set_title(f'{titulo}\nMediana={formatar_reais(med)} | IQR={formatar_reais(q3-q1)} | Outliers={n_outliers}', fontsize=9)
    ax.set_xticks([])
    ax.yaxis.set_major_formatter(mticker.FuncFormatter(formatar_reais))
    ax.legend(fontsize=7, loc='upper right')

    # Rotula outliers com nome do órgão
    rotular_outliers(ax, serie, df['Entidade_Chave'].values)

# Remove eixo extra
