def carregar_json(caminho: str) -> pd.DataFrame:
    """Lê um arquivo JSON (lista ou objeto) e retorna um DataFrame."""
    for tentativa in [caminho, caminho + '.json']:
        if os.path.exists(tentativa):
            with open(tentativa, 'r', encoding='utf-8') as f:
                conteudo = json.load(f)
            if isinstance(conteudo, list):
                return pd.json_normalize(conteudo)
            elif isinstance(conteudo, dict):
                # Tenta encontrar a lista dentro do dict
                for v in conteudo.values():
                    if isinstance(v, list):
                        return pd.json_normalize(v)
                return pd.json_normalize([conteudo])
    print(f"[AVISO] Arquivo não encontrado: {caminho}")
    return pd.DataFrame()

df_despesas  = carregar_json('/content/Documentos/Execucao_Detalhada_de_Despesas-2026')
