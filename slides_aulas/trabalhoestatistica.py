# 2. PADRONIZAÇÃO DO NOME DE ENTIDADE (chave de join)
# ============================================================
import unicodedata

def normalizar(nome):
    if pd.isna(nome):
        return "DESCONHECIDO"
    s = str(nome).upper().strip()
    s = unicodedata.normalize('NFKD', s)
    s = ''.join(c for c in s if not unicodedata.combining(c))
    return s

for df in [df_despesas, df_contratos, df_licitacoes]:
    if 'nomeEntidade' in df.columns:
        df['Entidade_Chave'] = df['nomeEntidade'].apply(normalizar)
    else:
        df['Entidade_Chave'] = 'DESCONHECIDO'

# ============================================================
# 3. CONVERSÃO DE TIPOS NUMÉRICOS
# ============================================================
def to_numeric(df, cols):
    for c in cols:
        if c in df.columns:
            df[c] = pd.to_numeric(
                df[c].astype(str).str.replace(',', '.', regex=False).str.replace(r'[^\d.\-]', '', regex=True),
                errors='coerce'
            ).fillna(0)
    return df

df_despesas  = to_numeric(df_despesas,  ['valorEmpenhado', 'valorPagoEmpenho', 'saldoAPagar'])
df_contratos = to_numeric(df_contratos, ['valorFinal', 'valorInicial'])
df_licitacoes = to_numeric(df_licitacoes, ['valorEstimado', 'valorHomologado'])

# ============================================================
# 4. AGRUPAMENTO POR ENTIDADE
# ============================================================
resumo_despesas = df_despesas.groupby('Entidade_Chave', as_index=False).agg(
    Total_Empenhado    =('valorEmpenhado',    'sum'),
    Total_Pago         =('valorPagoEmpenho',  'sum'),
    Saldo_A_Pagar      =('saldoAPagar',       'sum'),
)

resumo_contratos = df_contratos.groupby('Entidade_Chave', as_index=False).agg(
    Qtd_Contratos           =('numero',       'count'),
    Valor_Total_Contratos   =('valorFinal',   'sum'),
    Valor_Inicial_Contratos =('valorInicial', 'sum'),
)

# Participantes: suporta coluna numérica OU lista serializada
if 'participantes' in df_licitacoes.columns:
    df_licitacoes['qtd_part'] = df_licitacoes['participantes'].apply(
        lambda x: len(x) if isinstance(x, list) else (
            int(x) if str(x).isdigit() else 0
        )
    )
elif 'quantidadeParticipantes' in df_licitacoes.columns:
    df_licitacoes['qtd_part'] = pd.to_numeric(df_licitacoes['quantidadeParticipantes'], errors='coerce').fillna(0)
else:
    df_licitacoes['qtd_part'] = 0

id_licit = 'numeroProcesso' if 'numeroProcesso' in df_licitacoes.columns else df_licitacoes.columns[0]

resumo_licitacoes = df_licitacoes.groupby('Entidade_Chave', as_index=False).agg(
    Qtd_Licitacoes              =(id_licit,         'count'),
    Valor_Estimado_Licitacoes   =('valorEstimado',  'sum'),
    Valor_Homologado_Licitacoes =('valorHomologado','sum'),
    Media_Participantes         =('qtd_part',       'mean'),
)

# ============================================================
# 5. MERGE FINAL
# ============================================================
df = pd.merge(resumo_despesas,  resumo_contratos,  on='Entidade_Chave', how='outer')
df = pd.merge(df,               resumo_licitacoes, on='Entidade_Chave', how='outer')
df = df.fillna(0)

df['Ticket_Medio_Contrato'] = df['Valor_Total_Contratos'] / df['Qtd_Contratos'].replace(0, np.nan)
df['Ticket_Medio_Contrato'] = df['Ticket_Medio_Contrato'].fillna(0)

